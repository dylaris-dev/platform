type InstallerConfig struct {
	Type      string `json:"type"`      // "paper", "vanilla", "fabric", "forge", "neoforge", "library", "upload", "upload-zip", "import", "backup", "modpack", "technic"
	Version   string `json:"version"`   // MC version, e.g. "1.21.1"
	Loader    string `json:"loader"`    // Optional loader/build version (Fabric loader, Forge build, NeoForge version)
	URL       string `json:"url"`       // Direct download URL (for "import" / library fallback / modpack .mrpack)
	Path      string `json:"path"`      // Local library file path (for "library" type)
	Structure string `json:"structure"` // "direct" or "subfolder" (for "upload-zip")
	// modpack metadata. Type="modpack" expects URL to be a
	// .mrpack hosted on cdn.modrinth.com; the handler downloads, extracts
	// overrides, fans out every listed mod, then chains into the underlying
	// loader install (paper/fabric/forge/neoforge) using Loader+Version
	// from the .mrpack manifest.
	ModrinthProjectID   string `json:"modrinthProjectId,omitempty"`
	ModrinthVersionID   string `json:"modrinthVersionId,omitempty"`
	ModrinthProjectSlug string `json:"modrinthProjectSlug,omitempty"`
	// JavaImage + ServerUUID flow in from the setup command so installers
	// that need a real JVM (Forge / NeoForge) can run inside a temp
	// container with the user's chosen Java image instead of relying on
	// `java` being installed on the node host.
	JavaImage  string `json:"javaImage,omitempty"`
	ServerUUID string `json:"serverUuid,omitempty"`
	// WipePaths names what to CLEAR before installing, as tokens rather than
	// paths - see installer_wipe.go. Empty means install on top of whatever is
	// there, which is what every install did before this existed and is still
	// the right answer for a plain jar swap.
	WipePaths []string `json:"wipePaths,omitempty"`
	// Technic pack ("technic"): Core resolves the pack and says which of the
	// three shapes it is (installer_technic.go); TechnicMods are a Solder
	// build's archives. The Minecraft version is read from the pack itself.
	Variant     string       `json:"variant,omitempty"`
	TechnicMods []TechnicMod `json:"technicMods,omitempty"`
	// Software ("upload", "upload-zip" only) is installed over the uploaded
	// files - see installUploadSoftware. Empty keeps the upload's own jar.
	Software string `json:"software,omitempty"`
	// ModrinthFiles ("upload-zip" from a template only) are jars the template
	// references on Modrinth instead of carrying; downloaded after the software
	// install. An older node ignores the field, which is why Core refuses such
	// a template on one.
	ModrinthFiles []TemplateModrinthFile `json:"modrinthFiles,omitempty"`
	// ContainerPort is the port the server's container publishes, filled in by
	// the node (never sent by Core). A BungeeCord or Waterfall proxy is told to
	// listen on it, because their own default is 25577.
	ContainerPort int `json:"-"`
	// ProxyProtocol: Core switched this NEW server's real player IP forwarding
	// on and asks for the matching config (proxy_protocol_default.go). Only
	// ever sent with a first setup of Paper, Velocity, Waterfall or BungeeCord.
	ProxyProtocol bool `json:"proxyProtocol,omitempty"`
}

// CleanServerJars removes server JARs and cached/generated directories while preserving
// user data like worlds, plugins, mods, configs, etc.
func CleanServerJars(subServerDir string) error {
	// Directories to remove (generated by the server / installer)
	// Note: "libraries" is kept — Forge/NeoForge needs it for runtime dependencies
	removeDirs := []string{"versions", "cache", ".fabric", ".gradle"}
	for _, dir := range removeDirs {
		p := filepath.Join(subServerDir, dir)
		if _, err := os.Stat(p); err == nil {
			log.Printf("Removing directory: %s", dir)
			os.RemoveAll(p)
		}
	}

	// Remove all JAR files in the root of the sub-server directory
	entries, err := os.ReadDir(subServerDir)
	if err != nil {
		return fmt.Errorf("failed to read sub-server dir: %v", err)
	}
	for _, entry := range entries {
		if !entry.IsDir() && strings.HasSuffix(strings.ToLower(entry.Name()), ".jar") {
			p := filepath.Join(subServerDir, entry.Name())
			log.Printf("Removing JAR: %s", entry.Name())
			os.Remove(p)
		}
	}

	return nil
}

// InstallServer installs the server software into <serverDataPath>/<subServerName>/.
// For "upload" type, files are already in place via HTTP upload — nothing to do.
//
// manifest is what the install turned out to DESCRIBE, and only the "backup"
// type ever produces one: a Dylaris backup archive carries its own description
// and Core has no copy of it, so the reader that unpacks the archive is the only
// place it can be read. Every other installer is something Core already
// described - Core picked the loader, so Core knows the loader - and returns nil.
func InstallServer(serverDataPath, subServerName string, config InstallerConfig) ([]byte, error) {
	manifest, err := installServer(serverDataPath, subServerName, config)
	// Installers write as root; the server runs as the container's uid. Also
	// after a failed install: what it left behind is the operator's to fix,
	// and they cannot through a server that may not touch it.
	handInstalledTree(filepath.Join(serverDataPath, subServerName))
	return manifest, err
}

func installServer(serverDataPath, subServerName string, config InstallerConfig) (manifest []byte, err error) {
	destDir := filepath.Join(serverDataPath, subServerName)
	if err := os.MkdirAll(destDir, 0755); err != nil {
		return nil, fmt.Errorf("failed to create server dir: %v", err)
	}

	log.Printf("Starting Installation: %s (%s) -> %s", config.Type, config.Version, destDir)

	// Clear first, install second. The other order would delete files the
	// installer had just written - and on a failed install the operator would be
	// left with neither the old server nor the new one.
	if err := WipeBeforeInstall(destDir, config.WipePaths); err != nil {
		return nil, fmt.Errorf("preparing the directory failed: %w", err)
	}

	switch config.Type {
	case "paper":
		return nil, installPaper(destDir, config.Version, config.Loader)
	case "velocity", "waterfall":
		if err := installPaperMC(destDir, config.Type, config.Version); err != nil {
			return nil, err
		}
		if config.Type == "waterfall" {
			return nil, writeBungeeListener(destDir, config.ContainerPort)
		}
		return nil, nil
	case "bungeecord":
		if err := installBungeeCord(destDir, config.Version); err != nil {
			return nil, err
		}
		return nil, writeBungeeListener(destDir, config.ContainerPort)
	case "vanilla":
		return nil, installVanilla(destDir, config.Version)
	case "fabric":
		return nil, installFabric(destDir, config.Version, config.Loader)
	case "forge":
		return nil, installForge(destDir, config.Version, config.Loader, config.JavaImage, config.ServerUUID)
	case "neoforge":
		build := config.Loader
		if build == "" && config.Version != "" {
			// A version move sends the target Minecraft version and no build.
			v, err := resolveNeoForgeVersion(config.Version)
			if err != nil {
				return nil, err
			}
			build = v
		}
		return nil, installNeoForge(destDir, build, config.JavaImage, config.ServerUUID)
	case "library":
		return nil, installFromLibrary(destDir, config.Path, config.URL)
	case "import":
		if config.URL == "" {
			return nil, fmt.Errorf("import type requires a URL")
		}
		return nil, installFromURL(destDir, config.URL, downloadImportGuarded)
	case "upload":
		// Files pre-uploaded via HTTP to the sub-server directory.
		if config.Software == "" {
			log.Printf("Upload type: files already in %s, skipping installer", destDir)
			return nil, nil
		}
		return nil, installUploadSoftware(serverDataPath, subServerName, config)
	case "upload-zip":
		if err := installFromUploadZip(destDir, config.Structure); err != nil {
			return nil, err
		}
		if config.Software == "" {
			// Checked here rather than at the first start: an upload that only
			// carries its jar under versions/ (Paper) or a launcher script used
			// to install "successfully" and then fail every start. A modpack
			// server pack gets the loader it declares installed.
			err = makeUploadLaunchable(destDir, config)
		} else {
			err = installUploadSoftware(serverDataPath, subServerName, config)
		}
		if err != nil {
			return nil, err
		}
		return nil, installTemplateModrinth(destDir, config.ModrinthFiles)
	case "backup":
		// A Dylaris backup archive, uploaded into the sub-server directory the
		// same way an upload-zip install finds its zip there. The only installer
		// that reports something back: the archive describes itself.
		return installFromBackupArchive(destDir)
	case "modpack":
		return nil, installModpack(destDir, config)
	case "technic":
		return nil, installTechnic(destDir, config)
	default:
		return nil, fmt.Errorf("unknown installer type: %s", config.Type)
	}
}

// uploadSoftware is what may be installed over an upload: the plain server
// installers, never another source such as a URL import. The proxies are here
// for proxy templates, which Core sends as upload-zip with the proxy as software.
var uploadSoftware = map[string]bool{"paper": true, "vanilla": true, "fabric": true, "forge": true, "neoforge": true,
	"velocity": true, "waterfall": true, "bungeecord": true}

// installUploadSoftware installs the chosen server software over uploaded
// files. Worlds, plugins, mods and configs stay; the jars in the top folder and
// versions/ go, because the start picks whichever jar it finds first, not the
// one just installed. libraries/ goes when the new software is Forge/NeoForge
// or the upload carries a Forge/NeoForge argfile, which outranks any jar.
func installUploadSoftware(serverDataPath, subServerName string, config InstallerConfig) error {
	if !uploadSoftware[config.Software] {
		return fmt.Errorf("unsupported server software %q", config.Software)
	}
	destDir := filepath.Join(serverDataPath, subServerName)
	wipe := []string{WipeJars, WipeVersions}
	if config.Software == "forge" || config.Software == "neoforge" || resolveLaunch(destDir).Mode == launchArgfile {
		wipe = append(wipe, WipeLibraries)
	}
	next := config
	next.Type = config.Software
	next.Software = ""
	next.WipePaths = wipe
	_, err := installServer(serverDataPath, subServerName, next)
	return err
}

// installFabric downloads the Fabric server launcher. Resolves loader/installer
// versions from Fabric's meta service when the caller leaves them blank.
// Result lands as fabric-server-launch.jar in destDir.
func installFabric(dir, mcVersion, loaderVersion string) error {
	if loaderVersion == "" {
		v, err := resolveFabricLoader(mcVersion, "")
		if err != nil {
			return err
		}
		loaderVersion = v
	}

	// Pick the most recent stable installer (server-launcher itself is the
	// final artifact; this is just for the URL).
	var installers []struct {
		Version string `json:"version"`
		Stable  bool   `json:"stable"`
	}
	if err := fetchJSON("https://meta.fabricmc.net/v2/versions/installer", &installers); err != nil {
		return fmt.Errorf("fabric installer lookup failed: %v", err)
	}
	installerVersion := ""
	for _, i := range installers {
		if i.Stable {
			installerVersion = i.Version
			break
		}
	}
	if installerVersion == "" && len(installers) > 0 {
		installerVersion = installers[0].Version
	}
	if installerVersion == "" {
		return fmt.Errorf("no Fabric installer version available")
	}

	url := fmt.Sprintf("https://meta.fabricmc.net/v2/versions/loader/%s/%s/%s/server/jar",
		mcVersion, loaderVersion, installerVersion)
	log.Printf("Downloading Fabric server launcher (mc=%s loader=%s installer=%s)", mcVersion, loaderVersion, installerVersion)
	return downloadFile(url, filepath.Join(dir, "fabric-server-launch.jar"))
}

// resolveFabricLoader is the loader a blank want means for mcVersion (the
// newest stable, else the newest), or want itself once Fabric lists it for
// that version.
func resolveFabricLoader(mcVersion, want string) (string, error) {
	var loaders []struct {
		Loader struct {
			Version string `json:"version"`
			Stable  bool   `json:"stable"`
		} `json:"loader"`
	}
	if err := fetchJSON(fmt.Sprintf("https://meta.fabricmc.net/v2/versions/loader/%s", mcVersion), &loaders); err != nil {
		return "", fmt.Errorf("fabric loader lookup failed: %v", err)
	}
	if want != "" {
		for _, l := range loaders {
			if l.Loader.Version == want {
				return want, nil
			}
		}
		return "", fmt.Errorf("no Fabric loader %s for MC %s", want, mcVersion)
	}
	for _, l := range loaders {
		if l.Loader.Stable {
			return l.Loader.Version, nil
		}
	}
	if len(loaders) > 0 && loaders[0].Loader.Version != "" {
		return loaders[0].Loader.Version, nil
	}
	return "", fmt.Errorf("no Fabric loader available for MC %s", mcVersion)
}

// installQuilt lays down what Quilt's own installer does for a server: the
// libraries of Quilt's server launch profile under libraries/, a
// quilt-server-launch.jar that is only a manifest naming them, and the vanilla
// server.jar its launcher loads. Quilt's meta has no ready server jar the way
// Fabric's does, and Fabric's cannot stand in: it has no Quilt loader versions.
func installQuilt(dir, mcVersion, loaderVersion string) error {
	var profile struct {
		LauncherMainClass string `json:"launcherMainClass"`
		Libraries         []struct {
			Name string `json:"name"`
			URL  string `json:"url"`
		} `json:"libraries"`
	}
	if err := fetchJSON(fmt.Sprintf("https://meta.quiltmc.org/v3/versions/loader/%s/%s/server/json",
		url.PathEscape(mcVersion), url.PathEscape(loaderVersion)), &profile); err != nil {
		return fmt.Errorf("quilt launch profile lookup failed: %v", err)
	}
	if profile.LauncherMainClass == "" || len(profile.Libraries) == 0 {
		return fmt.Errorf("quilt launch profile for %s/%s is incomplete", mcVersion, loaderVersion)
	}
	root, err := os.OpenRoot(dir)
	if err != nil {
		return err
	}
	defer root.Close()
	var classPath []string
	for _, lib := range profile.Libraries {
		rel, ok := mavenJarPath(lib.Name)
		if !ok || !strings.HasPrefix(lib.URL, "https://") {
			return fmt.Errorf("quilt library %q from %q refused", lib.Name, lib.URL)
		}
		rel = "libraries/" + rel
		// Through the Root, so a planted libraries symlink is refused rather
		// than followed by the download below.
		if err := root.MkdirAll(filepath.Dir(rel), 0o755); err != nil {
			return fmt.Errorf("quilt library %s: %w", lib.Name, err)
		}
		if err := downloadFile(strings.TrimSuffix(lib.URL, "/")+"/"+strings.TrimPrefix(rel, "libraries/"), filepath.Join(dir, filepath.FromSlash(rel))); err != nil {
			return fmt.Errorf("quilt library %s: %w", lib.Name, err)
		}
		classPath = append(classPath, rel)
	}
	f, err := createIn(root, "quilt-server-launch.jar", 0o644)
	if err != nil {
		return err
	}
	zw := zip.NewWriter(f)
	w, err := zw.Create("META-INF/MANIFEST.MF")
	if err == nil {
		_, err = io.WriteString(w, manifestHeader("Manifest-Version", "1.0")+
			manifestHeader("Main-Class", profile.LauncherMainClass)+
			manifestHeader("Class-Path", strings.Join(classPath, " "))+"\r\n")
	}
	if cerr := zw.Close(); err == nil {
		err = cerr
	}
	if cerr := f.Close(); err == nil {
		err = cerr
	}
	if err != nil {
		return fmt.Errorf("writing quilt-server-launch.jar: %w", err)
	}
	log.Printf("Installed Quilt server launcher (mc=%s loader=%s)", mcVersion, loaderVersion)
	return installVanilla(dir, mcVersion)
}

// mavenJarPath turns group:artifact:version[:classifier] into the jar's path
// in a Maven repository (the classifier ignored, as Quilt's installer does).
// Every segment must be a plain name: the coordinates come from a third party
// and become a path inside the server.
func mavenJarPath(name string) (string, bool) {
	parts := strings.SplitN(name, ":", 4)
	if len(parts) < 3 {
		return "", false
	}
	group := strings.Split(parts[0], ".")
	for _, seg := range append(group, parts[1], parts[2]) {
		if !validate.IsPlainFileName(seg) {
			return "", false
		}
	}
	artifact, version := parts[1], parts[2]
	return strings.Join(group, "/") + "/" + artifact + "/" + version + "/" + artifact + "-" + version + ".jar", true
}

// manifestHeader is one JAR manifest header, wrapped the way the format
// requires: no line over 72 bytes, continuations start with a space. Java
// refuses an over-long line, and a Class-Path of every library is far over.
func manifestHeader(name, value string) string {
	line := name + ": " + value
	var b strings.Builder
	for first := true; ; first = false {
		n := 72
		if !first {
			b.WriteString(" ")
			n = 71
		}
		if len(line) <= n {
			b.WriteString(line + "\r\n")
			return b.String()
		}
		b.WriteString(line[:n] + "\r\n")
		line = line[n:]
	}
}

// installForge resolves the recommended/latest Forge build via promotions_slim.json
// (or uses the caller-supplied build), downloads the installer JAR and runs it
// inside a one-shot container built from the user's chosen Java image. No
// host-level Java install required.
func installForge(dir, mcVersion, build, javaImage, serverUUID string) error {
	if build == "" {
		b, err := resolveForgeBuild(mcVersion)
		if err != nil {
			return err
		}
		build = b
	}

	log.Printf("Downloading Forge installer (mc=%s build=%s)", mcVersion, build)
	return runLoaderInstaller(dir, "forge", forgeInstallerURL(mcVersion, build), "_forge-installer.jar", javaImage, serverUUID, "--installServer")
}

// resolveForgeBuild is the build a blank Forge loader means for mcVersion:
// the recommended promotion, else the latest.
func resolveForgeBuild(mcVersion string) (string, error) {
	var promos struct {
		Promos map[string]string `json:"promos"`
	}
	if err := fetchJSON("https://files.minecraftforge.net/net/minecraftforge/forge/promotions_slim.json", &promos); err != nil {
		return "", fmt.Errorf("forge promotions lookup failed: %v", err)
	}
	if b := promos.Promos[mcVersion+"-recommended"]; b != "" {
		return b, nil
	}
	if b := promos.Promos[mcVersion+"-latest"]; b != "" {
		return b, nil
	}
	return "", fmt.Errorf("no Forge build available for MC %s", mcVersion)
}

func forgeInstallerURL(mcVersion, build string) string {
	combined := mcVersion + "-" + build
	return fmt.Sprintf("https://maven.minecraftforge.net/net/minecraftforge/forge/%s/forge-%s-installer.jar", combined, combined)
}

// resolveVersionMoveTarget asks upstream whether there is anything to install
// for cfg, and returns the loader build the install is to use. A version move
// calls it BEFORE the stop: the target list comes from Modrinth, not from the
// loaders, so a version a loader has no build for yet could be chosen, and
// the install only found out after every player had been disconnected.
func resolveVersionMoveTarget(cfg InstallerConfig) (string, error) {
	switch cfg.Type {
	case "paper":
		_, err := paperMCBuildFor("paper", cfg.Version, cfg.Loader)
		return cfg.Loader, err
	case "fabric":
		return resolveFabricLoader(cfg.Version, cfg.Loader)
	case "forge":
		if cfg.Loader == "" {
			return resolveForgeBuild(cfg.Version)
		}
		return cfg.Loader, checkInstallerExists(forgeInstallerURL(cfg.Version, cfg.Loader))
	case "neoforge":
		if cfg.Loader == "" {
			return resolveNeoForgeVersion(cfg.Version)
		}
		// Unlike Forge's mc+build coordinate, a NeoForge build's URL does not
		// carry the Minecraft version, so a build from another line HEADs fine
		// and would install a loader the moved mods cannot run on.
		mc := "1.20.1"
		if !strings.HasPrefix(cfg.Loader, "47.") && !strings.HasPrefix(cfg.Loader, "1.20.1-") {
			mc = neoForgeMinecraft(strings.SplitN(cfg.Loader, "-", 2)[0])
		}
		if mc != "" && cfg.Version != "" && mc != cfg.Version {
			return "", fmt.Errorf("NeoForge build %s is for Minecraft %s, not %s", cfg.Loader, mc, cfg.Version)
		}
		return cfg.Loader, checkInstallerExists(neoForgeInstallerURL(cfg.Loader))
	}
	return cfg.Loader, nil
}

// checkInstallerExists HEADs a loader installer jar without downloading it.
func checkInstallerExists(u string) error {
	req, err := http.NewRequest(http.MethodHead, u, nil)
	if err != nil {
		return err
	}
	resp, err := installerMetaClient.Do(req)
	if err != nil {
		return fmt.Errorf("installer lookup failed: %v", err)
	}
	resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return fmt.Errorf("no installer at %s (HTTP %d)", u, resp.StatusCode)
	}
	return nil
}

// installNeoForge resolves the requested NeoForge version (or latest if blank)
// from the Maven metadata, downloads the installer JAR and runs --install-server
// inside a one-shot Java container.
func installNeoForge(dir, version, javaImage, serverUUID string) error {
	if version == "" {
		v, err := resolveNeoForgeVersion("")
		if err != nil {
			return err
		}
		version = v
	}

	log.Printf("Downloading NeoForge installer (version=%s)", version)
	return runLoaderInstaller(dir, "neoforge", neoForgeInstallerURL(version), "_neoforge-installer.jar", javaImage, serverUUID, "--install-server")
}

// neoForgeInstallerURL is the installer jar for a NeoForge build. The 1.20.1
// line (47.x) predates the rename and is published as net.neoforged:forge
// under 1.20.1-<build>; everything later is net.neoforged:neoforge:<build>.
func neoForgeInstallerURL(version string) string {
	if strings.HasPrefix(version, "47.") {
		version = "1.20.1-" + version
	}
	if strings.HasPrefix(version, "1.20.1-") {
		return fmt.Sprintf("https://maven.neoforged.net/releases/net/neoforged/forge/%s/forge-%s-installer.jar", version, version)
	}
	return fmt.Sprintf("https://maven.neoforged.net/releases/net/neoforged/neoforge/%s/neoforge-%s-installer.jar", version, version)
}

// resolveNeoForgeVersion reads the Maven metadata and picks the version a
// blank build means for mc (pickNeoForgeVersion).
func resolveNeoForgeVersion(mc string) (string, error) {
	metaURL := "https://maven.neoforged.net/releases/net/neoforged/neoforge/maven-metadata.xml"
	if mc == "1.20.1" {
		// The 47.x line is only in the pre-rename artifact (neoForgeInstallerURL).
		metaURL = "https://maven.neoforged.net/releases/net/neoforged/forge/maven-metadata.xml"
	}
	resp, err := installerMetaClient.Get(metaURL)
	if err != nil {
		return "", fmt.Errorf("neoforge metadata fetch failed: %v", err)
	}
	defer resp.Body.Close()
	var meta neoForgeMetadata
	if err := xml.NewDecoder(resp.Body).Decode(&meta); err != nil {
		return "", fmt.Errorf("neoforge metadata parse failed: %v", err)
	}
	version := pickNeoForgeVersion(meta, mc)
	if version == "" && mc != "" {
		return "", fmt.Errorf("no NeoForge version for Minecraft %s found in metadata", mc)
	}
	if version == "" {
		return "", fmt.Errorf("no NeoForge version found in metadata")
	}
	return version, nil
}

type neoForgeMetadata struct {
	Versioning struct {
		Latest   string `xml:"latest"`
		Release  string `xml:"release"`
		Versions struct {
			Version []string `xml:"version"`
		} `xml:"versions"`
	} `xml:"versioning"`
}

// pickNeoForgeVersion is the NeoForge version a blank loader means. With no
// Minecraft version it is the newest overall, as before. With one it is the
// newest build FOR that version: a version move sends the target Minecraft
// version and no build, and the newest overall belongs to whatever Minecraft
// line came out last, so a move to 1.21.1 installed NeoForge for 1.21.10.
// A stable build wins over a newer pre-release; a line that only has
// pre-releases gets the newest of those. mc may also name a NeoForge version
// itself, which is then taken as it is.
func pickNeoForgeVersion(meta neoForgeMetadata, mc string) string {
	v := meta.Versioning
	if mc == "" {
		if v.Release != "" {
			return v.Release
		}
		if v.Latest != "" {
			return v.Latest
		}
		if n := len(v.Versions.Version); n > 0 {
			return v.Versions.Version[n-1]
		}
		return ""
	}
	best, bestPre := "", ""
	for _, c := range v.Versions.Version {
		if c == mc {
			return c
		}
		// The legacy forge artifact names its builds "1.20.1-47.1.106"; the
		// build is what follows, and 47.x does not map through neoForgeMinecraft.
		target := ""
		if b, ok := strings.CutPrefix(c, "1.20.1-"); ok {
			c, target = b, "1.20.1"
		}
		base, _, pre := strings.Cut(c, "-")
		if target == "" {
			target = neoForgeMinecraft(base)
		}
		if target != mc {
			continue
		}
		if !pre {
			if best == "" || compareDotted(base, strings.SplitN(best, "-", 2)[0]) > 0 {
				best = c
			}
		} else if bestPre == "" || compareDotted(base, strings.SplitN(bestPre, "-", 2)[0]) > 0 {
			bestPre = c
		}
	}
	if best != "" {
		return best
	}
	return bestPre
}

// neoForgeMinecraft maps a NeoForge build to the Minecraft version it targets,
// "" when it cannot tell. Below 26 the minor is Minecraft's patch ("21.1.264"
// is 1.21.1, "21.0.x" is 1.21); from 26 on the build starts with the Minecraft
// version ("26.1.2.5" is 26.1.2, "26.3.0.89" is 26.3). Core's
// services.NeoForgeMinecraft is the same mapping; keep the two in step.
func neoForgeMinecraft(build string) string {
	parts := strings.Split(build, ".")
	if len(parts) < 3 {
		return ""
	}
	nums := make([]int, len(parts))
	for i, p := range parts {
		n, err := strconv.Atoi(p)
		if err != nil || len(p) > 9 {
			return ""
		}
		nums[i] = n
	}
	if nums[0] == 0 {
		return ""
	}
	if nums[0] >= 26 {
		mc := parts[0] + "." + parts[1]
		if len(parts) >= 4 && nums[2] != 0 {
			mc += "." + parts[2]
		}
		return mc
	}
	mc := "1." + parts[0]
	if nums[1] != 0 {
		mc += "." + parts[1]
	}
	return mc
}

// compareDotted compares two all-numeric dotted versions part by part.
func compareDotted(a, b string) int {
	pa, pb := strings.Split(a, "."), strings.Split(b, ".")
	for i := 0; i < len(pa) || i < len(pb); i++ {
		var x, y int
		if i < len(pa) {
			x, _ = strconv.Atoi(pa[i])
		}
		if i < len(pb) {
			y, _ = strconv.Atoi(pb[i])
		}
		if x != y {
			if x < y {
				return -1
			}
			return 1
		}
	}
	return 0
}

