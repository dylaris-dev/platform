// runLoaderInstaller downloads a Forge/NeoForge installer jar into dir and
// runs it there. The jar goes whatever happens - the removal is registered
// before the download, so a failed one leaves no empty jar behind - and the
// installer's own log (<jar>.log, a megabyte in every server) goes after a
// successful run; after a failed one it stays for whoever has to look.
func runLoaderInstaller(dir, name, installerURL, jarName, javaImage, serverUUID string, args ...string) error {
	installerPath := filepath.Join(dir, jarName)
	defer os.Remove(installerPath)
	if err := downloadFile(installerURL, installerPath); err != nil {
		return fmt.Errorf("%s installer download failed: %v", name, err)
	}
	if err := clearLoaderLaunchDirs(dir); err != nil {
		return err
	}
	log.Printf("Running %s %s inside %s ...", name, strings.Join(args, " "), javaImage)
	if err := runJavaInstallerFn(serverUUID, filepath.Base(dir), javaImage, jarName, args...); err != nil {
		return err
	}
	if err := os.Remove(installerPath + ".log"); err != nil && !os.IsNotExist(err) {
		log.Printf("%s installer: could not remove its log: %v", name, err)
	}
	return nil
}

// runJavaInstaller wraps the installer-JAR execution inside a one-shot Java
// container. The sub-server directory (not the server root) is mounted at
// /data so /data/<installerJAR> resolves where the JAR was actually
// downloaded to. Previously the bind mounted the server root and the cmd
// looked for the JAR at /data/_forge-installer.jar — but the JAR lives in
// <server-dir>/<sub-server>/_forge-installer.jar, so Java exited 1 with
// no useful stderr (JVM "Unable to access jarfile" beats stdcopy to it).
// installerTimeout bounds one installer run; a real Forge install downloads
// its libraries in a few minutes.
const installerTimeout = 30 * time.Minute

func runJavaInstaller(serverUUID, subServerName, javaImage, installerJAR string, args ...string) error {
	if dockerManager == nil {
		return fmt.Errorf("docker manager unavailable — installer cannot run")
	}
	if javaImage == "" {
		return fmt.Errorf("installer requires a Java image (set during setup)")
	}
	if subServerName == "" {
		return fmt.Errorf("installer requires a sub-server name (cannot resolve mount path)")
	}
	cmd := append([]string{"java", "-jar", "/data/" + installerJAR}, args...)
	// An installer jar can be the tenant's own (a server pack ships one), so
	// one that never exits must not hold the server in "installing" forever.
	ctx, cancel := context.WithTimeout(context.Background(), installerTimeout)
	defer cancel()
	logs, err := dockerManager.RunInstallerContainer(ctx, serverUUID, subServerName, javaImage, cmd)
	if err != nil {
		if logs != "" {
			return fmt.Errorf("%w\n%s", err, logs)
		}
		return err
	}
	return nil
}

